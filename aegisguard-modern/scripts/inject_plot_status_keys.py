def dump(value):
    if isinstance(value, list):
        return "\n".join(["  - " + yaml_str(line) for line in value])
    return yaml_str(value)

def yaml_str(s):
    if s is None:
        return "''"
    text = str(s)
    if any(c in text for c in ":#{}[],&*!|>'\"%@`") or text.strip() != text or text == "":
        return "'" + text.replace("'", "''") + "'"
    return text

