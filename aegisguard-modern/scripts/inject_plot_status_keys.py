MARKER = "# --- 1.3.0 claim status menu polish ---"

def render_block(keys):
    lines = ["", MARKER]
    for key, value in keys.items():
        if isinstance(value, list):
            lines.append(f"{key}:")
            lines.append(dump(value))
        else:
            lines.append(f"{key}: {dump(value)}")
    lines.append("")
    return "\n".join(lines)

def upsert(path: Path, keys: dict):
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    if MARKER in text:
        text = text.split(MARKER)[0].rstrip() + "\n"
    path.write_text(text.rstrip() + "\n" + render_block(keys), encoding="utf-8")

def main():
    english_keys = PACKS["modern_english"].keys()
    for lang in LANGS:
        keys = PACKS[lang]
        missing = [k for k in english_keys if k not in keys]
        extra = [k for k in keys if k not in english_keys]
        if missing or extra:
            raise SystemExit(f"{lang} missing={missing} extra={extra}")
        upsert(ROOT / "lang" / lang / "guis.yml", keys)
        upsert(ROOT / "codex" / f"{lang}.yml", keys)
        print(f"updated {lang}")

if __name__ == "__main__":
    main()
